function pack(args: {
  app: string;
  canvas?: string;
  surface: string;
  alt: string;
  input?: string;
  hover: string;
  border: string;
  borderStrong: string;
  text: string;
  text2: string;
  text3: string;
  inv?: string;
  accent: string;
  accentHover: string;
  accentMuted: string;
  ok: string;
  okBg: string;
  warn: string;
  warnBg: string;
  bad: string;
  badBg: string;
  info?: string;
  infoBg?: string;
  chrome: string;
  chromeBorder?: string;
  chromeText: string;
  chromeTitle: string;
  chromeMuted: string;
  railHover: string;
  railActive: string;
  railActiveBg: string;
  tableHead?: string;
  pathIdle?: string;
  markFill: string;
  voice: string;
  voiceInk: string;
}): ThemeTokens {
  return {
    "bg-app": args.app,
    "bg-canvas": args.canvas || args.app,
    "bg-dashlet": args.surface,
    "bg-dashlet-alt": args.alt,
    "bg-input": args.input || args.surface,
    "bg-hover": args.hover,
    border: args.border,
    "border-strong": args.borderStrong,
    text: args.text,
    "text-2": args.text2,
    "text-3": args.text3,
    "text-inv": args.inv || args.chromeTitle,
    accent: args.accent,
    "accent-hover": args.accentHover,
    "accent-muted": args.accentMuted,
    ok: args.ok,
    "ok-bg": args.okBg,
    warn: args.warn,
    "warn-bg": args.warnBg,
    bad: args.bad,
    "bad-bg": args.badBg,
    info: args.info || args.accent,
    "info-bg": args.infoBg || args.accentMuted,
    "chrome-bg": args.chrome,
    "chrome-border": args.chromeBorder || args.border,
    "chrome-text": args.chromeText,
    "chrome-title": args.chromeTitle,
    "chrome-muted": args.chromeMuted,
    "rail-hover": args.railHover,
    "rail-active": args.railActive,
    "rail-active-bg": args.railActiveBg,
    "table-head": args.tableHead || args.alt,
    "path-idle": args.pathIdle || args.borderStrong,
    "mark-fill": args.markFill,
    "voice-stage": args.voice,
    "voice-ink": args.voiceInk,
  };
}

