export const PALETTE_BY_ID = Object.fromEntries(PALETTES.map((palette) => [palette.id, palette])) as Record<
  PaletteId,
  Palette
>;

export function resolveScheme(displayMode: DisplayMode, query?: { matches: boolean }): Scheme {
  if (displayMode === "light") return "light";
  if (displayMode === "dark") return "dark";
  if (query) return query.matches ? "dark" : "light";
  if (typeof window !== "undefined" && window.matchMedia) {
    return window.matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light";
  }
  return "light";
}

function withIntensity(tokens: ThemeTokens, intensity: Intensity): ThemeTokens {
  if (intensity === "standard") return tokens;
  if (intensity === "muted") {
    return {
      ...tokens,
      accent: `color-mix(in srgb, ${tokens.accent} 62%, ${tokens["text-3"]})`,
      "accent-hover": `color-mix(in srgb, ${tokens["accent-hover"]} 62%, ${tokens["text-3"]})`,
      "rail-active-bg": `color-mix(in srgb, ${tokens["rail-active-bg"]} 70%, ${tokens["chrome-bg"]})`,
    };
  }
  return {
    ...tokens,
    accent: `color-mix(in srgb, ${tokens.accent} 88%, white)`,
    "accent-hover": tokens["accent-hover"],
    "rail-active-bg": `color-mix(in srgb, ${tokens["rail-active-bg"]} 80%, ${tokens.accent})`,
  };
}

export function tokensFor(paletteId: PaletteId, scheme: Scheme, intensity: Intensity): ThemeTokens {
  const palette = PALETTE_BY_ID[paletteId] || PALETTE_BY_ID.vigil;
  return withIntensity(scheme === "dark" ? palette.dark : palette.light, intensity);
}

export function applyAppearance(opts: { palette: PaletteId; displayMode: DisplayMode; intensity: Intensity }) {
  if (typeof document === "undefined") return;
  const scheme = resolveScheme(opts.displayMode);
  const tokens = tokensFor(opts.palette, scheme, opts.intensity);
  const root = document.documentElement;
  root.dataset.theme = scheme;
  root.dataset.scheme = scheme;
  root.dataset.palette = opts.palette;
  root.dataset.intensity = opts.intensity;
  root.style.colorScheme = scheme;
  for (const [key, value] of Object.entries(tokens)) {
    root.style.setProperty(`--${key}`, value);
  }
  root.style.setProperty("--rail-bg", tokens["chrome-bg"]);
  root.style.setProperty("--rail-border", tokens["chrome-border"]);
  root.style.setProperty("--rail-text", tokens["chrome-text"]);
  root.style.setProperty("--rail-text-2", tokens["chrome-muted"]);
  root.style.setProperty("--topbar-bg", tokens["chrome-bg"]);
  root.style.setProperty(
    "--focus-ring",
    scheme === "dark" ? `0 0 0 2px ${tokens["bg-app"]}, 0 0 0 4px ${tokens.accent}` : `0 0 0 2px #fff, 0 0 0 4px ${tokens.accent}`,
  );
  root.style.setProperty(
    "--shadow-dashlet",
    scheme === "dark" ? "0 1px 2px rgba(0, 0, 0, 0.35)" : "0 1px 2px rgba(11, 31, 58, 0.06), 0 8px 20px rgba(11, 31, 58, 0.04)",
  );
}

export function swatchesFor(palette: Palette, scheme: Scheme): [string, string, string] {
  const tokens = scheme === "dark" ? palette.dark : palette.light;
  return [tokens["chrome-bg"], tokens.accent, tokens["bg-app"]];
}
